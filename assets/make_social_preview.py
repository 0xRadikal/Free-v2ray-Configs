#!/usr/bin/env python3
"""Rasterises assets/social-preview.svg -> social-preview.png + social-preview.jpg.

Why raster copies of an SVG: X/Twitter cards and Facebook reject SVG for
og:image / twitter:image (JPG, PNG, WebP, GIF only), and GitHub's
Settings -> Social preview accepts only PNG, JPG or GIF under 1 MB. The SVG
itself is the source of truth and is generated by `make_assets.py` (social()).

  1280x640  GitHub's recommended social-preview size (2:1).
  PNG       uploaded as the repository's social preview (crisp text).
  JPEG      used as og:image / twitter:image by the dashboard (smaller).

The script refuses to write if any <text> overflows the canvas or its chip, so
a font fallback that renders wider than expected fails loudly instead of
shipping clipped text.

Requires: playwright + its Chromium, Pillow.
Run:      python3 assets/make_assets.py && python3 assets/make_social_preview.py
"""
import io
import os
import sys

from PIL import Image
from playwright.sync_api import sync_playwright

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "social-preview.svg")
W, H = 1280, 640
GITHUB_LIMIT = 1_000_000  # bytes — "under 1 MB" (GitHub docs)

# JS: every <text> must stay inside the canvas with a 20 px safety band, and a
# text that sits on a <rect> drawn immediately before it must fit inside it.
CHECK = """() => {
  // Two independent rules, each checked on real rendered geometry (getBBox):
  //  1. every <text> lies inside the canvas, with a 20 px safety band at the
  //     sides (X/Facebook crop 2:1 toward 1.91:1);
  //  2. a <text> tagged data-box="ID" lies inside the <rect id="ID"> it is
  //     drawn on, with 6 px padding. Explicit pairing — no sibling guessing.
  const bad = [];
  const svg = document.querySelector('svg');
  for (const t of svg.querySelectorAll('text')) {
    const b = t.getBBox();
    const label = t.textContent.trim();
    if (b.x < 20 || b.y < 6 || b.x + b.width > %d - 20 || b.y + b.height > %d - 6)
      bad.push('canvas: ' + label);
    const id = t.getAttribute('data-box');
    if (id) {
      const r = svg.getElementById(id);
      if (!r) { bad.push('missing box ' + id + ' for ' + label); continue; }
      const rb = r.getBBox();
      if (b.x < rb.x + 6 || b.x + b.width > rb.x + rb.width - 6)
        bad.push('box: ' + label + ' needs ' + Math.ceil(b.x + b.width - rb.x + 6) + ' px, box is ' + rb.width);
    }
  }
  return bad;
}""" % (W, H)


def main() -> int:
    svg = open(SRC, encoding="utf-8").read()
    html = ("<!doctype html><html><head><meta charset=utf-8><style>"
            "html,body{margin:0;background:#070C18}svg{display:block}</style></head>"
            f"<body>{svg}</body></html>")
    with sync_playwright() as p:
        b = p.chromium.launch()
        pg = b.new_page(viewport={"width": W, "height": H}, device_scale_factor=1)
        pg.set_content(html)
        pg.wait_for_timeout(500)
        bad = pg.evaluate(CHECK)
        png = pg.screenshot(clip={"x": 0, "y": 0, "width": W, "height": H})
        b.close()
    if bad:
        print("refusing to write — text does not fit:\n  " + "\n  ".join(bad))
        return 1
    im = Image.open(io.BytesIO(png)).convert("RGB")
    assert im.size == (W, H), im.size
    out_png = os.path.join(HERE, "social-preview.png")
    out_jpg = os.path.join(HERE, "social-preview.jpg")
    im.save(out_png, optimize=True)
    im.save(out_jpg, quality=90, optimize=True, progressive=True)
    for f in (out_png, out_jpg):
        size = os.path.getsize(f)
        print(f"  wrote {os.path.basename(f):22s} {size:8,d} B  {W}x{H}")
        if size >= GITHUB_LIMIT:
            print(f"  {os.path.basename(f)} is over GitHub's 1 MB social-preview limit")
            return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
